static const mid_t *mid_find(int mid)
{
    int lo = 0, hi = (int)(sizeof(mids) / sizeof(mids[0])) - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (mids[m].mid == mid) return &mids[m];
        if (mids[m].mid < mid) lo = m + 1; else hi = m - 1;
    }
    return NULL;
}

const char *dsc_mid_iso(int mid)
{
    const mid_t *m = mid_find(mid);
    return m ? m->iso : NULL;
}

const char *dsc_mid_country(int mid)
{
    int lo = 0, hi = (int)(sizeof(mids) / sizeof(mids[0])) - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (mids[m].mid == mid) return mids[m].name;
        if (mids[m].mid < mid) lo = m + 1; else hi = m - 1;
    }
    return NULL;
}
