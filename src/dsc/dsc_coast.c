static int cmp(const void *a, const void *b)
{
    uint32_t x = *(const uint32_t *)a, y = ((const coast_t *)b)->mmsi;
    return x < y ? -1 : x > y;
}

const char *dsc_coast_name(const char *mmsi)
{
    if (!mmsi || strlen(mmsi) != 9 || mmsi[0] != '0' || mmsi[1] != '0') return NULL;
    uint32_t m = 0;
    for (int i = 0; i < 9; ++i) {
        if (mmsi[i] < '0' || mmsi[i] > '9') return NULL;
        m = m * 10 + (uint32_t)(mmsi[i] - '0');
    }
    const coast_t *r = bsearch(&m, coast, sizeof(coast) / sizeof(coast[0]), sizeof(coast_t), cmp);
    return r ? r->name : NULL;
}
